const detect = (): Lang => {
  const stored = typeof localStorage === 'undefined' ? null : localStorage.getItem('ps.lang')
  if (stored === 'fr' || stored === 'en') return stored
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

let lang: Lang = detect()

export const getLang = () => lang
export const otherLang = (): Lang => (lang === 'fr' ? 'en' : 'fr')
export const setLang = (l: Lang) => { lang = l }

/** Change la langue et recharge : les textes sont lus au rendu, et certains au chargement. */
export function changeLang(l: Lang) {
  localStorage.setItem('ps.lang', l)
  location.reload()
}

/** Pour les nombres et le tri. */
export const locale = () => (lang === 'fr' ? 'fr-CA' : 'en-CA')

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text = (lang === 'fr' ? fr : en)[key]
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in params ? String(params[name]) : all))
}

/** Message du serveur : traduit d'après sa clé, sinon le texte reçu, qui est en anglais. */
export function serverMessage(key: string | null | undefined, message: string | null | undefined, params: Record<string, string | number> = {}): string {
  const k = `msg.${key}`
  return k in fr ? t(k as Key, params) : message ?? ''
}
